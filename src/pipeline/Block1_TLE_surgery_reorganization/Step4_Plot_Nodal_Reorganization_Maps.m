        cortical_hemisphere(startsWith( ...
            string(mapping_table.ENIGMA_Name), "7Networks_LH")) = "Left";
        if analysis_mode == "Original"
            cortical_hemisphere_interpretation = ...
                "Anatomical_" + cortical_hemisphere;
