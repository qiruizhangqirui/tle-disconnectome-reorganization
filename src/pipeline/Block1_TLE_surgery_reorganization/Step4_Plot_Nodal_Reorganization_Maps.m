                "Contralateral", height(mapping_table), 1);
            cortical_hemisphere_interpretation( ...
                cortical_hemisphere == "Left") = "Ipsilateral";
        end

        cortical_output_table = table( ...
            mapping_table.ENIGMA_Index, cortical_hemisphere, ...
            cortical_hemisphere_interpretation, ...
            mapping_table.Project_ROI_ID, cortical_roi_names, ...
            cortical_values, cortical_mask, ...
            'VariableNames', { ...
            'ENIGMA_Index', 'Hemisphere', ...
            'Hemisphere_Interpretation', 'Atlas_ROI_ID', ...
            'ROI_Name', 'Map_Value', 'Masked'});
        writetable( ...
            cortical_output_table, ...
            fullfile(enigma_input_dir, ...
            char(current_output_name + "_Schaefer100.csv")));

        %% Section 5.3.2 Write the subcortical input table

        subcortical_roi_ids = (1:16)';
        [~, subcortical_row_indices] = ismember( ...
            subcortical_roi_ids, current_roi_ids);
        subcortical_values_all = current_values(subcortical_row_indices);
        subcortical_mask_all = current_masked(subcortical_row_indices);
        subcortical_roi_names = current_roi_names(subcortical_row_indices);
        subcortical_hemisphere = repmat("Right", 16, 1);
        subcortical_hemisphere(startsWith( ...
            subcortical_roi_names, "Left")) = "Left";
        if analysis_mode == "Original"
            subcortical_hemisphere_interpretation = ...
                "Anatomical_" + subcortical_hemisphere;
        else
            subcortical_hemisphere_interpretation = ...
                repmat("Contralateral", 16, 1);
            subcortical_hemisphere_interpretation( ...
                subcortical_hemisphere == "Left") = "Ipsilateral";
        end

        subcortical_enigma_order = nan(16, 1);
        [~, enigma_order_indices] = ismember( ...
            subcortical_roi_ids, subcortical_enigma_roi_ids);
        supported_subcortical = enigma_order_indices > 0;
        subcortical_enigma_order(supported_subcortical) = ...
            enigma_order_indices(supported_subcortical);

        subcortical_output_table = table( ...
            subcortical_roi_ids, subcortical_roi_names, ...
            subcortical_hemisphere, ...
            subcortical_hemisphere_interpretation, ...
            subcortical_enigma_order, subcortical_values_all, ...
            subcortical_mask_all, supported_subcortical, ...
            'VariableNames', { ...
            'Atlas_ROI_ID', 'ROI_Name', 'Hemisphere', ...
            'Hemisphere_Interpretation', 'ENIGMA_Order', ...
            'Map_Value', 'Masked', 'Visualization_Supported'});
        writetable( ...
            subcortical_output_table, ...
            fullfile(enigma_input_dir, ...
            char(current_output_name + "_Subcortical.csv")));

        %% Section 5.3.3 Write the volumetric NIfTI map

        volume_data = zeros(size(atlas_data), 'single');
        for roi_index = 1:numel(current_roi_ids)
            if ~current_masked(roi_index) && ...
                    isfinite(current_values(roi_index))
                volume_data(atlas_data == current_roi_ids(roi_index)) = ...
                    single(current_values(roi_index));
            end
        end
        niftiwrite( ...
            volume_data, ...
            fullfile(enigma_input_dir, ...
            char(current_output_name + ".nii")), ...
            atlas_info, 'Compressed', true);

        if contains(current_value_field, "Normative_Z")
            current_colorbar_label = "Normative Z";
        elseif contains(current_value_field, "SD")
            current_colorbar_label = "Standard Deviation";
        elseif current_metric == metric_ncr
            current_colorbar_label = "NCR (1 minus r)";
        else
            current_colorbar_label = "NMR (%)";
        end

        %% Section 5.3.4 Render the cortical ENIGMA component

        cortical_figure = figure( ...
            'Visible', 'off', 'Color', 'white');
        plot_cortical_overlay( ...
            cortical_values, cortical_mask, ...
            'surface_name', 'conte69', ...
            'color_range', current_color_range, ...
            'cmap', current_colormap, ...
            'label_text', current_colorbar_label);
        print( ...
            cortical_figure, ...
            fullfile(figure_dir, ...
            char(current_output_name + "_Cortical.tiff")), ...
            '-dtiff', '-r300');
        close(cortical_figure);

        %% Section 5.3.5 Render the subcortical ENIGMA component

        [~, subcortical_plot_indices] = ismember( ...
            subcortical_enigma_roi_ids, current_roi_ids);
        subcortical_plot_values = current_values(subcortical_plot_indices);
        subcortical_plot_mask = current_masked(subcortical_plot_indices);
        subcortical_figure = figure( ...
            'Visible', 'off', 'Color', 'white');
        plot_subcortical_overlay( ...
            subcortical_plot_values, subcortical_plot_mask, ...
            'ventricles', 'False', ...
            'color_range', current_color_range, ...
            'cmap', current_colormap, ...
            'label_text', current_colorbar_label);
        print( ...
            subcortical_figure, ...
            fullfile(figure_dir, ...
            char(current_output_name + "_Subcortical.tiff")), ...
            '-dtiff', '-r300');
        close(subcortical_figure);
    end
end

%% Section 6 Calculate and plot cross center spatial correlations

correlation_metrics = [metric_ncr; metric_nmr];
correlation_raw_fields = [ ...
    "NCR_Mean_Raw"; "NMR_Mean_Raw_Percent"];
correlation_file_suffixes = ["NCR.tiff"; "NMR_Percent.tiff"];
correlation_colors = [0.75, 0.10, 0.10; 0.20, 0.40, 0.70];
n_correlation_rows = numel(correlation_metrics);

correlation_analysis_mode = ...
    repmat("Laterality_Normalized", n_correlation_rows, 1);
correlation_n_rois = zeros(n_correlation_rows, 1);
correlation_r = nan(n_correlation_rows, 1);
correlation_p = nan(n_correlation_rows, 1);
correlation_slope = nan(n_correlation_rows, 1);
correlation_intercept = nan(n_correlation_rows, 1);

% Pair centers by atlas ROI identity rather than relying on CSV row order.
% The fixed input contract provides one row per ROI and identical ROI sets.
[~, jlh_roi_order] = ismember( ...
    tju_laterality_normalized_results.ROI_ID, ...
    jlh_laterality_normalized_results.ROI_ID);

for metric_index = 1:n_correlation_rows
    current_metric = correlation_metrics(metric_index);
    current_raw_field = correlation_raw_fields(metric_index);

    x_values = tju_laterality_normalized_results.( ...
        char(current_raw_field));
    y_values = jlh_laterality_normalized_results.( ...
        char(current_raw_field));
    y_values = y_values(jlh_roi_order);
    tju_masked = logical( ...
        tju_laterality_normalized_results.Group_Masked);
    jlh_masked = logical( ...
        jlh_laterality_normalized_results.Group_Masked);
    jlh_masked = jlh_masked(jlh_roi_order);

    % Every ROI outside both cohort specific group masks enters the spatial
    % correlation. A nonfinite raw mean outside the masks is a fixed input
    % problem and stops the analysis rather than changing the ROI set.
    unmasked_pair = ~tju_masked & ~jlh_masked;
    if any(~isfinite(x_values(unmasked_pair))) || ...
            any(~isfinite(y_values(unmasked_pair)))
        error( ...
            'Step4:NonfiniteCrossCenterRawMean', ...
            ['A cross center raw mean is nonfinite outside the ' ...
            'group masks for %s.'], ...
            current_metric);
    end
    x_values = x_values(unmasked_pair);
    y_values = y_values(unmasked_pair);

    current_r = corr(x_values, y_values, 'Type', 'Pearson');
    current_degrees_freedom = numel(x_values) - 2;

    % Use the equivalent beta distribution form of the two-sided Pearson
    % test to preserve very small nonzero P values.
    current_p = betainc( ...
        1 - current_r ^ 2, current_degrees_freedom / 2, 0.5);
    fit_coefficients = polyfit(x_values, y_values, 1);
    fit_x = linspace(min(x_values), max(x_values), 100);
    fit_y = polyval(fit_coefficients, fit_x);

    correlation_n_rois(metric_index) = numel(x_values);
    correlation_r(metric_index) = current_r;
    correlation_p(metric_index) = current_p;
    correlation_slope(metric_index) = fit_coefficients(1);
    correlation_intercept(metric_index) = fit_coefficients(2);

    correlation_figure = figure( ...
        'Visible', 'off', 'Color', 'white', ...
        'Position', [100, 100, 650, 600]);
    scatter( ...
        x_values, y_values, 45, correlation_colors(metric_index, :), ...
        'filled', 'MarkerFaceAlpha', 0.75);
    hold on;
    plot(fit_x, fit_y, 'k-', 'LineWidth', 2);
    box on;
    set(gca, ...
        'Position', [0.15, 0.14, 0.75, 0.72], ...
        'FontName', 'Arial', 'FontSize', 12);
    xlabel('TJU mean', 'FontName', 'Arial', 'FontSize', 12);
    ylabel('JLH mean', 'FontName', 'Arial', 'FontSize', 12);
    title_handle = title( ...
        replace( ...
        "Laterality_Normalized: " + current_metric, "_", " "), ...
        'FontName', 'Arial', 'FontSize', 13, 'FontWeight', 'bold');
    set(title_handle, 'Units', 'normalized');
    title_position = get(title_handle, 'Position');
    set(title_handle, 'Position', ...
        [title_position(1), 1.04, title_position(3)]);

    p_text = sprintf('P = %.2e', current_p);
    statistics_text = sprintf( ...
        'r = %.3f\n%s\nN = %d', ...
        current_r, p_text, numel(x_values));
    text( ...
        0.05, 0.95, statistics_text, ...
        'Units', 'normalized', 'VerticalAlignment', 'top', ...
        'FontName', 'Arial', 'FontSize', 12, ...
        'Interpreter', 'tex');

    print( ...
        correlation_figure, ...
        fullfile(results_root, ...
        char( ...
        "Cross_Center_Laterality_Normalized_Spatial_Correlation_" + ...
        correlation_file_suffixes(metric_index))), ...
        '-dtiff', '-r300');
    close(correlation_figure);
end

correlation_table = table( ...
    correlation_analysis_mode, correlation_metrics, ...
    correlation_n_rois, ...
    correlation_r, correlation_p, ...
    correlation_slope, correlation_intercept, ...
    'VariableNames', { ...
    'Analysis_Mode', 'Metric', 'N_ROIs_Paired', ...
    'Pearson_R', 'Pearson_P', ...
    'Regression_Slope', 'Regression_Intercept'});
writetable( ...
    correlation_table, ...
